#!/usr/bin/env python3
"""Where the datum corrections of `src/crs/corrections.rs` hold: the areas
`src/crs/areas.rs` holds, one for each correction.

A correction is a polynomial fitted at the stops of a country's register
(`tools/crs_corrections.py`). Within the stops it mends the old network to a
few decimetres; beyond them it extrapolates, some hundred metres off within a
day's journey of the border. Its area is the cells of a tenth of a degree, in
longitude and latitude, that hold a stop of the register: a position in no
such cell is left to the Helmert transformation alone, within two metres.

Only the standard library is used. The registers are those the corrections
are fitted at:

    python3 tools/crs_areas.py \\
        --austria haltestellen.csv --switzerland actual-date-swiss-service-point.csv
"""

import argparse
import csv
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CELLS_PER_DEGREE = 10


def austria(path):
    """Longitude and latitude of every stop of the Austrian register."""
    with open(path, encoding="utf-8") as file:
        for row in csv.DictReader(file):
            try:
                yield float(row["hst_x"]), float(row["hst_y"])
            except ValueError:
                continue


def switzerland(path):
    """Longitude and latitude of every Swiss service point, as the register
    states them in WGS 84; those abroad left out, as the fit leaves them."""
    with open(path, encoding="utf-8-sig") as file:
        for row in csv.DictReader(file, delimiter=";"):
            if row["isoCountryCode"] != "CH" or not row["lv95East"] or not row["wgs84East"]:
                continue
            yield float(row["wgs84East"]), float(row["wgs84North"])


def cells(stops):
    """The cells holding a stop: column and row, in tenths of a degree."""
    return {
        (math.floor(lon * CELLS_PER_DEGREE), math.floor(lat * CELLS_PER_DEGREE))
        for lon, lat in stops
        if math.isfinite(lon) and math.isfinite(lat)
    }


def rust_area(name, doc, held, stops):
    west = min(column for column, _ in held)
    south = min(row for _, row in held)
    columns = max(column for column, _ in held) - west + 1
    rows = max(row for _, row in held) - south + 1
    words = [0] * ((columns * rows + 63) // 64)
    for column, row in held:
        bit = (row - south) * columns + (column - west)
        words[bit // 64] |= 1 << (bit % 64)
    numbers = "\n".join(f"        0x{word:016x}," for word in words)
    return f"""{doc}
/// {len(held)} cells, from {stops} stops.
pub(super) const {name}: Area = Area {{
    west: {west},
    south: {south},
    columns: {columns},
    rows: {rows},
    cells: &[
{numbers}
    ],
}};
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--austria", required=True, help="haltestellen.csv of the Austrian register")
    parser.add_argument("--switzerland", required=True, help="the Swiss service point register")
    arguments = parser.parse_args()

    at = list(austria(arguments.austria))
    ch = list(switzerland(arguments.switzerland))
    header = """// Generated by tools/crs_areas.py — do not edit by hand.
//
// Where each correction of `corrections.rs` holds: the cells of a tenth of a
// degree holding a stop of the register it is fitted at, from the stops of the
// Austrian register (data.gv.at, CC BY 4.0) and the Swiss register
// (opentransportdata.swiss).

use super::Area;
"""
    tables = [
        rust_area("MGI", "/// MGI (Austria): the cells of the stops of the Austrian register.", cells(at), len(at)),
        rust_area("CH1903", "/// CH1903 (Switzerland, LV03): the cells of the Swiss service points.", cells(ch), len(ch)),
    ]
    with open(os.path.join(ROOT, "src/crs/areas.rs"), "w", encoding="utf-8") as file:
        file.write(header + "\n" + "\n".join(tables))


if __name__ == "__main__":
    main()
